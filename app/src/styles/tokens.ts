// Builds tokens.css from the café's theme, marca/tokens.json: its colors, fonts, sizes and effects.
// Run by scripts/tokens.mjs (npm run tokens) and checked by tokens.test.ts: if the theme changes, it's regenerated.
// The token names (--fondo, --tinta…) are the theme's, in Spanish, and are kept as they are: the styles use them.

interface Token {
  name: string;
  value: string;
}

interface TextStyle {
  name: string;
  fontSize: string;
  lineHeight: number;
  fontWeight: number;
  letterSpacing?: string;
  fontStyle?: string;
}

export interface Tokens {
  color: { tokens: Token[] };
  efecto: { tokens: Token[] };
  type: {
    /** The font files, in public/fonts/. None: the families fall back on the phone's own. */
    fonts: { family: string; file: string; weight: string; style: string }[];
    families: Record<string, string>;
    groups: { name: string; styles: TextStyle[] }[];
  };
  spacing: { tokens: Token[] };
  radius: { tokens: Token[] };
  tamano: { tokens: Token[] };
  trazo: { tokens: Token[] };
}

/** A color of the theme, by name: colorOf(tokens, "fondo"). */
export function colorOf(tokens: Tokens, name: string): string {
  const token = tokens.color.tokens.find((t) => t.name === name);
  if (!token) throw new Error(`marca/tokens.json has no ${name} color.`);
  return token.value;
}

/**
 * The theme writes the text in px; the app gives it in rem, so it follows the text size the person chose in
 * their browser. 18px is 1.125rem with the browser's 16px.
 */
const rem = (px: string) => `${Number.parseFloat(px) / 16}rem`;

const variables = (tokens: Token[]) =>
  tokens.map((token) => `  --${token.name}: ${token.value};`).join("\n");

export function tokensCss(tokens: Tokens): string {
  const fonts = tokens.type.fonts
    .map(
      (font) =>
        `@font-face {\n  font-family: ${font.family};\n  src: url("/fonts/${font.file.split("/").pop()}") format("woff2");\n  font-weight: ${font.weight};\n  font-style: ${font.style};\n  font-display: swap;\n}\n\n`,
    )
    .join("");

  const families = Object.entries(tokens.type.families)
    .map(([name, family]) => `  --${name}: ${family};`)
    .join("\n");

  const texts = tokens.type.groups
    .flatMap((group) => group.styles)
    .map((style) =>
      [
        `  --${style.name}-size: ${rem(style.fontSize)};`,
        `  --${style.name}-line-height: ${style.lineHeight};`,
        `  --${style.name}-weight: ${style.fontWeight};`,
        `  --${style.name}-tracking: ${style.letterSpacing ?? "normal"};`,
        `  --${style.name}-style: ${style.fontStyle ?? "normal"};`,
      ].join("\n"),
    )
    .join("\n");

  return `/* Generated by scripts/tokens.mjs from marca/tokens.json. Don't edit by hand: npm run tokens. */

${fonts}:root {
  /* Color */
${variables(tokens.color.tokens)}

  /* Effects */
${variables(tokens.efecto.tokens)}

  /* Families */
${families}

  /* Text */
${texts}

  /* Spacing */
${variables(tokens.spacing.tokens)}

  /* Radii */
${variables(tokens.radius.tokens)}

  /* Sizes */
${variables(tokens.tamano.tokens)}

  /* Strokes */
${variables(tokens.trazo.tokens)}
}
`;
}

/** The browser's bar color, for root.tsx: the theme's fondo. */
export function themeTs(tokens: Tokens): string {
  return `// Generated by scripts/tokens.mjs from marca/tokens.json. Don't edit by hand: npm run tokens.

/** The browser's bar, the same as the page's background (fondo). */
export const THEME_COLOR = "${colorOf(tokens, "fondo")}";
`;
}
